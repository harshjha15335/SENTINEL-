"""Contained blob storage for evidence files and generated packets.

Keys are generated by the server (``<merchant>/<kind>/<uuid>``); user-supplied names never reach
a filesystem path. Nothing stored here is served as static content: downloads go through
authorised API routes only.
"""

import os
import re
import uuid
from functools import lru_cache
from pathlib import Path
from typing import Protocol

from sqlalchemy import delete, select
from sqlalchemy.orm import Session

from app.core.config import StorageBackend, get_settings
from app.core.errors import DomainError
from app.models import StoredBlob

_KEY = re.compile(r"^[0-9a-f-]{36}/(evidence|packets)/[0-9a-f-]{36}$")


class StorageError(DomainError):
    status_code = 500
    code = "storage_error"


def new_key(merchant_id: uuid.UUID, kind: str) -> str:
    key = f"{merchant_id}/{kind}/{uuid.uuid4()}"
    check_key(key)
    return key


def check_key(key: str) -> None:
    if not _KEY.fullmatch(key):
        raise StorageError("Invalid storage key")


class BlobStorage(Protocol):
    name: str

    def put(self, db: Session, key: str, data: bytes) -> None: ...

    def get(self, db: Session, key: str) -> bytes: ...

    def delete(self, db: Session, key: str) -> None: ...


class LocalStorage:
    """Files under a private directory. For local development and single-host deployments."""

    name = "local"

    def __init__(self, root: str | Path) -> None:
        self.root = Path(root).resolve()

    def _path(self, key: str) -> Path:
        check_key(key)
        path = (self.root / key).resolve()
        if not path.is_relative_to(self.root):
            raise StorageError("Invalid storage key")
        return path

    def put(self, db: Session, key: str, data: bytes) -> None:
        path = self._path(key)
        path.parent.mkdir(parents=True, exist_ok=True, mode=0o700)
        tmp = path.with_suffix(".tmp")
        with open(tmp, "wb") as fh:
            fh.write(data)
        os.chmod(tmp, 0o600)
        tmp.replace(path)

    def get(self, db: Session, key: str) -> bytes:
        path = self._path(key)
        try:
            return path.read_bytes()
        except FileNotFoundError as exc:
            raise StorageError("Stored file is missing") from exc

    def delete(self, db: Session, key: str) -> None:
        self._path(key).unlink(missing_ok=True)


class DatabaseStorage:
    """Bytes in PostgreSQL (``stored_blobs``). For hosts without a persistent disk.

    Writes join the caller's transaction, so a failed upload leaves no orphaned blob.
    """

    name = "database"

    def put(self, db: Session, key: str, data: bytes) -> None:
        check_key(key)
        db.add(StoredBlob(key=key, body=data))
        db.flush()

    def get(self, db: Session, key: str) -> bytes:
        check_key(key)
        body = db.scalar(select(StoredBlob.body).where(StoredBlob.key == key))
        if body is None:
            raise StorageError("Stored file is missing")
        return body

    def delete(self, db: Session, key: str) -> None:
        check_key(key)
        db.execute(delete(StoredBlob).where(StoredBlob.key == key))


@lru_cache
def get_storage() -> BlobStorage:
    settings = get_settings()
    if settings.storage_backend is StorageBackend.DATABASE:
        return DatabaseStorage()
    root = Path(settings.storage_dir)
    if not root.is_absolute():
        root = Path(__file__).resolve().parents[2] / root
    return LocalStorage(root)


def storage_for(name: str) -> BlobStorage:
    """The backend a record was written with (it may differ from the current default)."""
    current = get_storage()
    if current.name == name:
        return current
    if name == "database":
        return DatabaseStorage()
    settings = get_settings()
    root = Path(settings.storage_dir)
    if not root.is_absolute():
        root = Path(__file__).resolve().parents[2] / root
    return LocalStorage(root)
