PACKET_NOTICE = (
    "Internal evidence packet generated by SENTINEL. It is not a PayPal document and has not "
    "been submitted to PayPal. Merchant-provided files are included as supplied and are not "
    "verified by SENTINEL or PayPal."
)
AI_LABEL = (
    "AI-generated analysis: produced by a language model from the records listed. Verify "
    "before relying on it."
)

_ORIGIN = {
    "LIVE_SANDBOX": "Live sandbox (PayPal sandbox API / verified webhook)",
    "SIMULATED": "Simulated (offline fixture gateway; never reached PayPal)",
    "SYNTHETIC_DEMO": "Synthetic demo (generated scenario data; not a PayPal payment)",
    "MERCHANT_PROVIDED": "Merchant provided (not verified by PayPal)",
}

_styles = getSampleStyleSheet()
H1 = ParagraphStyle("h1", parent=_styles["Heading1"], fontSize=16, spaceAfter=4)
H2 = ParagraphStyle("h2", parent=_styles["Heading2"], fontSize=12, spaceBefore=10, spaceAfter=4)
BODY = ParagraphStyle("body", parent=_styles["BodyText"], fontSize=9, leading=12)
SMALL = ParagraphStyle(
    "small", parent=BODY, fontSize=8, leading=10, textColor=colors.HexColor("#444444")
)
NOTE = ParagraphStyle(
    "note",
    parent=BODY,
    backColor=colors.HexColor("#FFF6DD"),
    borderColor=colors.HexColor("#E0B84C"),
    borderWidth=0.5,
    borderPadding=4,
    spaceBefore=4,
    spaceAfter=6,
)
QUOTE = ParagraphStyle("quote", parent=BODY, leftIndent=10, textColor=colors.HexColor("#333333"))


def _p(text: object, style: ParagraphStyle = BODY) -> Paragraph:
    # Every dynamic value is escaped: ReportLab paragraphs interpret markup.
    return Paragraph(escape(str(text)).replace("\n", "<br/>"), style)


def _dt(value: datetime | None) -> str:
    return value.astimezone(UTC).strftime("%Y-%m-%d %H:%M UTC") if value else "—"


def _money(minor: int, currency: str) -> str:
    return f"{minor / 100:,.2f} {currency}"


def _table(rows: list[list[Any]], widths: list[float] | None = None, header: bool = False) -> Table:
    data = [[c if isinstance(c, Paragraph) else _p(c, SMALL) for c in row] for row in rows]
    t = Table(data, colWidths=widths, hAlign="LEFT")
    style = [
        ("GRID", (0, 0), (-1, -1), 0.25, colors.HexColor("#BBBBBB")),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("LEFTPADDING", (0, 0), (-1, -1), 4),
        ("RIGHTPADDING", (0, 0), (-1, -1), 4),
    ]
    if header:
        style.append(("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#EEF2F7")))
    else:
        style.append(("BACKGROUND", (0, 0), (0, -1), colors.HexColor("#F4F6F8")))
    t.setStyle(TableStyle(style))
    return t


def _chronology(
    case: Case,
    events: list[PaymentEvent],
    evidence: list[EvidenceArtifact],
    runs: list[InvestigationRun],
    approvals: list[ApprovalRequest],
    assessment_at: datetime | None,
) -> list[tuple[datetime, str, str]]:
    t = case.transaction
    origin = t.data_origin.value
    items: list[tuple[datetime, str, str]] = [(t.created_at, "Payment record created", origin)]
    if t.occurred_at:
        items.append((t.occurred_at, f"Payment {t.status.value.lower().replace('_', ' ')}", origin))
    for ev in events:
        items.append(
            (
                ev.received_at,
                f"Provider event {ev.provider_event_type} ({ev.verification_status.value.lower()})",
                ev.data_origin.value,
            )
        )
    if t.refunded_at:
        items.append((t.refunded_at, "Refund recorded", origin))
    if t.disputed_at:
        items.append((t.disputed_at, "Dispute recorded", origin))
    if assessment_at:
        items.append((assessment_at, "Risk assessment recorded (model-generated)", "SENTINEL"))
    items.append((case.created_at, f"Review case opened ({case.source.value.lower()})", "SENTINEL"))
    for e in evidence:
        items.append(
            (e.created_at, f"Evidence uploaded ({e.category.value.lower()})", "MERCHANT_PROVIDED")
        )
    for r in runs:
        if r.completed_at:
            items.append(
                (
                    r.completed_at,
                    f"Investigation {r.status.value.lower()} ({r.mode.value.lower()})",
                    "SENTINEL",
                )
            )
    for a in approvals:
        items.append(
            (a.created_at, f"Approval requested: {a.action_type.value.lower()}", "SENTINEL")
        )
        if a.decided_at:
            items.append(
                (
                    a.decided_at,
                    f"Approval {a.status.value.lower()}: {a.action_type.value.lower()}",
                    "SENTINEL",
                )
            )
    if case.resolved_at:
        items.append((case.resolved_at, "Case resolved", "SENTINEL"))
    return sorted(items, key=lambda x: x[0])


def build_pdf(db: Session, case: Case, generated_by: str) -> tuple[bytes, dict[str, Any]]:
    t = case.transaction
    assessment = latest_for(db, case.merchant_id, t.id)
    events = list(
        db.scalars(
            select(PaymentEvent)
            .where(
                PaymentEvent.transaction_id == t.id, PaymentEvent.merchant_id == case.merchant_id
            )
            .order_by(PaymentEvent.received_at)
        )
    )
    evidence = list(
        db.scalars(
            select(EvidenceArtifact)
            .where(
                EvidenceArtifact.case_id == case.id,
                EvidenceArtifact.merchant_id == case.merchant_id,
            )
            .order_by(EvidenceArtifact.created_at)
        ).unique()
    )
    runs = list(
        db.scalars(
            select(InvestigationRun)
            .where(
                InvestigationRun.case_id == case.id,
                InvestigationRun.merchant_id == case.merchant_id,
            )
            .order_by(InvestigationRun.created_at)
        ).unique()
    )
    approvals = list(
        db.scalars(
            select(ApprovalRequest)
            .where(
                ApprovalRequest.case_id == case.id, ApprovalRequest.merchant_id == case.merchant_id
            )
            .order_by(ApprovalRequest.created_at)
        ).unique()
    )
    note_count = len(list(db.scalars(select(CaseNote.id).where(CaseNote.case_id == case.id))))
    run = latest_completed(db, case.merchant_id, case.id)
    now = datetime.now(UTC)

    story: list[Any] = [
        _p("SENTINEL evidence packet", H1),
        _p(f"{case.title} · case {case.id}", SMALL),
        _p(f"Generated {_dt(now)} by {generated_by}", SMALL),
        _p(PACKET_NOTICE, NOTE),
        _p("1. Case", H2),
        _table(
            [
                ["Case id", str(case.id)],
                [
                    "Status",
                    case.status.value + (f" ({case.resolution.value})" if case.resolution else ""),
                ],
                ["Priority", case.priority.value],
                ["Opened", f"{_dt(case.created_at)} by {case.source.value.lower()}"],
                ["Due", _dt(case.due_at)],
                ["Analyst notes", f"{note_count} (not reproduced in this packet)"],
            ],
            [40 * mm, 130 * mm],
        ),
        _p("2. Payment and provenance", H2),
        _table(
            [
                ["Data origin", _ORIGIN[t.data_origin.value]],
                ["Amount", _money(t.amount_minor, t.currency)],
                ["Item", f"{t.product.name if t.product else 'Unknown item'} x {t.quantity}"],
                ["Status", f"{t.status.value} (provider status {t.provider_status or '—'})"],
                ["PayPal order id", t.paypal_order_id or "—"],
                ["PayPal capture id", t.paypal_capture_id or "—"],
                ["Payer reference", t.payer_reference or "—"],
                ["Occurred", _dt(t.occurred_at)],
                ["SENTINEL payment id", str(t.id)],
            ],
            [40 * mm, 130 * mm],
        ),
        _p("3. Chronology of recorded events", H2),
        _p(
            "Only events SENTINEL has recorded. No shipping, delivery or buyer-contact events "
            "exist unless listed here.",
            SMALL,
        ),
        _table(
            [["When", "Event", "Source"]]
            + [
                [_dt(when), what, _ORIGIN.get(src, src)]
                for when, what, src in _chronology(
                    case,
                    events,
                    evidence,
                    runs,
                    approvals,
                    assessment.created_at if assessment else None,
                )
            ],
            [35 * mm, 85 * mm, 50 * mm],
            header=True,
        ),
        _p("4. Risk assessment (model-generated, shadow policy)", H2),
    ]
    if assessment:
        contribs = sorted(
            assessment.explanation.get("contributions", []),
            key=lambda c: abs(float(c.get("contribution", 0.0))),
            reverse=True,
        )[:5]
        story += [
            _table(
                [
                    ["Model", f"{assessment.model_version} ({assessment.feature_version})"],
                    [
                        "Score / band",
                        f"{assessment.risk_score * 100:.1f}% · {assessment.risk_band.value}",
                    ],
                    [
                        "Shadow policy",
                        f"{assessment.policy_decision.value} (recorded only; never enforced)",
                    ],
                    ["Scored", _dt(assessment.created_at)],
                ],
                [40 * mm, 130 * mm],
            ),
            Spacer(1, 4),
            _table(
                [["Main drivers (TreeSHAP)", "Value", "Effect (log-odds)"]]
                + [
                    [
                        c.get("label", c.get("feature")),
                        f"{float(c.get('value', 0)):g}",
                        f"{float(c.get('contribution', 0)):+.3f}",
                    ]
                    for c in contribs
                ],
                [100 * mm, 30 * mm, 40 * mm],
                header=True,
            ),
            _p("Limitations", SMALL),
        ] + [_p(f"• {lim}", SMALL) for lim in assessment.limitations]
    else:
        story.append(_p("This payment has not been scored.", BODY))

    story += [
        _p("5. Evidence inventory", H2),
        _p("Files uploaded by the merchant. Categories are the uploader's labels.", SMALL),
    ]
    if evidence:
        story.append(
            _table(
                [["Id", "Declared category", "Type / size", "SHA-256", "Uploaded", "Text"]]
                + [
                    [
                        str(e.id)[:8],
                        e.category.value,
                        f"{e.content_type} · {e.size_bytes:,} B",
                        e.sha256[:16] + "…",
                        _dt(e.created_at),
                        e.extraction_status.value,
                    ]
                    for e in evidence
                ],
                [16 * mm, 32 * mm, 36 * mm, 34 * mm, 30 * mm, 22 * mm],
                header=True,
            )
        )
    else:
        story.append(_p("No evidence has been uploaded for this case.", BODY))

    excerpts: list[tuple[str, str]] = []
    findings: dict[str, Any] | None = run.findings if run else None
    if findings:
        for ref in findings.get("evidence_references", []):
            if ref.get("excerpt"):
                excerpts.append((ref["evidence_id"], ref["excerpt"]))
    story.append(_p("6. Referenced excerpts", H2))
    if excerpts:
        story.append(
            _p(
                "Verbatim quotes from merchant-provided documents, checked against their "
                "extracted text.",
                SMALL,
            )
        )
        for eid, text in excerpts:
            story.append(KeepTogether([_p(f"Evidence {eid[:8]}", SMALL), _p(f"“{text}”", QUOTE)]))
    else:
        story.append(_p("No excerpts were referenced.", BODY))

    story.append(_p("7. Investigation findings", H2))
    if run and findings:
        label = AI_LABEL if run.mode is InvestigationMode.AI_AGENT else DETERMINISTIC_LABEL
        story += [
            _p(label, NOTE),
            _p(
                f"Run {run.id} · {run.mode.value} · {run.provider}/{run.model_name} · prompt "
                f"{run.prompt_version} · completed {_dt(run.completed_at)}",
                SMALL,
            ),
            _p(findings["summary"]),
        ]
        for title, key, field in (
            ("Verified facts", "verified_facts", "statement"),
            ("Risk indicators", "risk_indicators", "description"),
            ("Counter-indicators", "counter_indicators", "description"),
        ):
            rows = findings.get(key, [])
            story.append(_p(title, SMALL))
            if not rows:
                story.append(_p("None.", SMALL))
            for row in rows:
                cites = ", ".join(f"{s['kind']}:{s['id'][:8]}" for s in row["sources"])
                story.append(_p(f"• {row[field]} [{cites}]", BODY))
        story += [
            _p(f"Recommended action: {findings['recommended_action']}", BODY),
            _p(findings["recommendation_rationale"], BODY),
            _p("Limitations", SMALL),
        ] + [_p(f"• {lim}", SMALL) for lim in findings.get("limitations", [])]
    else:
        story.append(_p("No completed investigation for this case.", BODY))

    story.append(_p("8. Missing information", H2))
    missing = [i["label"] for i in evidence_checklist(evidence) if not i["provided"]]
    if findings:
        missing += [m for m in findings.get("missing_information", []) if m not in missing]
    story += [_p(f"• {m}", BODY) for m in missing] or [_p("Nothing listed as missing.", BODY)]

    story.append(_p("9. Human review status", H2))
    story.append(
        _p(
            f"Case status: {case.status.value}"
            + (f", resolution {case.resolution.value}" if case.resolution else "")
            + ". No financial action has been executed by SENTINEL for this case.",
            BODY,
        )
    )
    if approvals:
        story.append(
            _table(
                [["Requested", "Action", "Status", "Requested by", "Decided by"]]
                + [
                    [
                        _dt(a.created_at),
                        a.action_type.value,
                        a.status.value,
                        a.requested_by.email if a.requested_by else "—",
                        (
                            a.decision.decided_by.email
                            if a.decision and a.decision.decided_by
                            else "—"
                        ),
                    ]
                    for a in approvals
                ],
                [30 * mm, 42 * mm, 22 * mm, 38 * mm, 38 * mm],
                header=True,
            )
        )
    else:
        story.append(_p("No approval requests.", BODY))

    buf = io.BytesIO()

    def footer(canvas: Any, doc: Any) -> None:
        canvas.saveState()
        canvas.setFont("Helvetica", 7)
        canvas.setFillColor(colors.HexColor("#666666"))
        canvas.drawString(
            15 * mm,
            10 * mm,
            f"SENTINEL internal evidence packet · case {case.id} · not submitted to PayPal",
        )
        canvas.drawRightString(195 * mm, 10 * mm, f"Page {doc.page}")
        canvas.restoreState()

    doc = SimpleDocTemplate(
        buf,
        pagesize=A4,
        leftMargin=15 * mm,
        rightMargin=15 * mm,
        topMargin=15 * mm,
        bottomMargin=18 * mm,
        title=f"SENTINEL evidence packet {case.id}",
        author="SENTINEL",
        subject="Internal evidence packet",
    )
    doc.build(story, onFirstPage=footer, onLaterPages=footer)
    contents = {
        "case_id": str(case.id),
        "transaction_id": str(t.id),
        "data_origin": t.data_origin.value,
        "risk_assessment_id": str(assessment.id) if assessment else None,
        "investigation_run_id": str(run.id) if run else None,
        "investigation_mode": run.mode.value if run else None,
        "evidence_ids": [str(e.id) for e in evidence],
        "approval_request_ids": [str(a.id) for a in approvals],
        "payment_event_ids": [str(e.id) for e in events],
        "excerpt_count": len(excerpts),
        "generated_at": now.isoformat(),
    }
    return buf.getvalue(), contents


def generate(db: Session, principal: Principal, case_id: uuid.UUID) -> EvidencePacket:
    case = get_case(db, principal.merchant_id, case_id)
    pdf, contents = build_pdf(db, case, principal.user.email)
    storage = get_storage()
    key = new_key(principal.merchant_id, "packets")
    sha = hashlib.sha256(pdf).hexdigest()
    packet = EvidencePacket(
        merchant_id=case.merchant_id,
        case_id=case.id,
        investigation_run_id=uuid.UUID(contents["investigation_run_id"])
        if contents["investigation_run_id"]
        else None,
        generated_by_user_id=principal.user.id,
        sha256=sha,
        size_bytes=len(pdf),
        page_count=len(PdfReader(io.BytesIO(pdf)).pages),
        storage_backend=storage.name,
        storage_key=key,
        contents=contents,
    )
    db.add(packet)
    db.flush()
    storage.put(db, key, pdf)
    audit.record_for_case(
        db,
        case,
        "packet.generated",
        principal.user.id,
        entity_type="evidence_packet",
        entity_id=packet.id,
        sha256=sha,
        size_bytes=len(pdf),
        evidence_count=len(contents["evidence_ids"]),
        investigation_run_id=contents["investigation_run_id"],
    )
    try:
        db.commit()
    except Exception:
        storage.delete(db, key)
        raise
    return packet


def list_for_case(db: Session, merchant_id: uuid.UUID, case_id: uuid.UUID) -> list[EvidencePacket]:
    case = get_case(db, merchant_id, case_id)
    return list(
        db.scalars(
            select(EvidencePacket)
            .where(EvidencePacket.case_id == case.id, EvidencePacket.merchant_id == merchant_id)
            .order_by(EvidencePacket.created_at.desc())
        ).unique()
    )


def get_packet(
    db: Session, merchant_id: uuid.UUID, case_id: uuid.UUID, packet_id: uuid.UUID
) -> EvidencePacket:
    packet = db.scalar(
        select(EvidencePacket).where(
            EvidencePacket.id == packet_id,
            EvidencePacket.case_id == case_id,
            EvidencePacket.merchant_id == merchant_id,
        )
    )
    if packet is None:
        raise NotFoundError("Evidence packet not found")
    return packet


def read_for_download(
    db: Session, principal: Principal, case_id: uuid.UUID, packet_id: uuid.UUID
) -> tuple[EvidencePacket, bytes]:
    case = get_case(db, principal.merchant_id, case_id)
    packet = get_packet(db, principal.merchant_id, case.id, packet_id)
    data = storage_for(packet.storage_backend).get(db, packet.storage_key)
    audit.record_for_case(
        db,
        case,
        "packet.downloaded",
        principal.user.id,
        entity_type="evidence_packet",
        entity_id=packet.id,
        sha256=packet.sha256,
    )
    db.commit()
    return packet, data
